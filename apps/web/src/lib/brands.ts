/**
 * Resolve the appropriate brand list for a category + subcategory.
 * Falls back to a generic CLUB_BRANDS list if no specific match.
 */
export function getBrandsFor(category: string, subcategory?: string | null): string[] {
  const sub = (subcategory || '').toLowerCase();

  switch (category) {
    case 'Clubs':
      return CLUB_BRANDS;
    case 'Shafts, Grips & Heads':
      if (sub === 'shafts') return SHAFT_BRANDS;
      if (sub === 'grips') return GRIP_BRANDS;
      if (sub === 'heads') return HEAD_BRANDS;
      return CLUB_BRANDS;
    case 'Clothing':
      if (sub === 'hats & caps') return HAT_BRANDS;
      if (sub === 'sunglasses') return SUNGLASSES_BRANDS;
      if (sub === 'gloves') return GLOVE_BRANDS;
      return CLOTHING_BRANDS;
    case 'Shoes':
      return SHOE_BRANDS;
    case 'Accessories':
      if (sub === 'bags') return BAG_BRANDS;
      if (sub === 'headcovers') return HEADCOVER_BRANDS;
      if (sub === 'tees') return TEE_BRANDS;
      if (sub === 'rangefinders') return RANGEFINDER_BRANDS;
      if (sub === 'launch monitors') return LAUNCH_MONITOR_BRANDS;
      if (sub === 'gps devices') return GPS_BRANDS;
      if (sub === 'towels') return TOWEL_BRANDS;
      if (sub === 'golf trolleys') return TROLLEY_BRANDS;
      return CLOTHING_BRANDS;
    case 'Balls':
      return BALL_BRANDS;
    case 'Training Aids':
      return TRAINING_AID_BRANDS;
    default:
      return CLUB_BRANDS;
  }
}
